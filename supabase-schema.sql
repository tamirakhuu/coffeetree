  create table products (
    id bigint generated by default as identity primary key,
    name text not null,
    brand_id bigint references brands(id) on delete set null,
    category_id bigint references categories(id) on delete set null,
    subcategory text,
    origin text,
    tag text,
    color text default '#6B4226',
    description text,
    images jsonb default '[]'::jsonb,
    unit_label text,
    unit_price numeric default 0,
    unit_original_price numeric, -- хямдрахаас өмнөх үнэ (зөвхөн хямдралтай үед бөглөнө)
    unit_stock int default 0,
    warehouse_unit_stock int default 0, -- агуулах дахь нөөц (ширхэг) — эндээс дэлгүүрийн unit_stock рүү татдаг
    box_label text,
    box_price numeric default 0,
    box_original_price numeric, -- хямдрахаас өмнөх үнэ (зөвхөн хямдралтай үед бөглөнө)
    box_per_box int default 1,
    box_stock int default 0,
    warehouse_box_stock int default 0, -- агуулах дахь нөөц (хайрцаг) — эндээс дэлгүүрийн box_stock рүү татдаг
    bulk_qty int, -- бөөний үнэ бодогдож эхлэх ширхэгийн тоо (барааны хувиар өөр өөр байдаг)
    unified_stock boolean default false, -- хайрцгаар ирж, ширхэгээр задарч зардаг бол box_stock-ыг unit_stock-оос автоматаар тооцно
    created_at timestamptz default now()
  );

  create table orders (
    order_number text primary key,
    user_id uuid references auth.users(id) on delete set null,
    customer_name text,
    phone text,
    address text,
    subtotal numeric,
    status text default 'pending', -- pending | processing | shipped | done | cancelled
    receipt_type text default 'individual', -- individual | company
    register_number text, -- байгууллагын регистрийн дугаар (receipt_type='company' үед)
    delivery_method text default 'pickup', -- pickup | delivery
    delivery_fee numeric default 0,
    box_count integer default 0, -- админ гараар оруулдаг хайрцгийн тоо
    created_at timestamptz default now()
  );

  create table order_items (
    id bigint generated by default as identity primary key,
    order_number text not null references orders(order_number) on delete cascade,
    product_id bigint references products(id) on delete set null,
    product_name text,
    option_type text, -- 'unit' | 'box'
    option_label text,
    unit_price numeric,
    qty int,
    line_total numeric
  );

  -- Агуулах ⇄ дэлгүүрийн шилжилтийн түүх (Тайлан хуудсанд харуулна)
  create table stock_transfers (
    id bigint generated by default as identity primary key,
    product_id bigint references products(id) on delete set null,
    product_name text not null,
    option_type text not null, -- 'unit' | 'box'
    direction text not null, -- 'to_store' (агуулахаас татсан) | 'to_warehouse' (дэлгүүрээс буцаасан)
    qty int not null,
    admin_email text,
    created_at timestamptz default now()
  );

