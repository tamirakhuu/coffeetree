// Optional isolated PostgreSQL test: node scripts/test-coffee-sql.mjs <PGlite package directory>
// Install PGlite in a temporary directory; it is not an application dependency.
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { testTrainingSQL } from './test-training-sql.mjs';
const { PGlite } = await import(pathToFileURL(resolve(process.argv[2], 'dist/index.js')).href);
const db = new PGlite();
try {
  await db.exec('create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key);');
  await db.exec(`
    create function auth.email() returns text language sql as $$ select null::text $$;
    create function auth.uid() returns uuid language sql as $$ select null::uuid $$;
    create schema storage;
    create table storage.objects(id bigint, bucket_id text);
    create publication supabase_realtime;
  `);
  const schema = await readFile('supabase-schema.sql', 'utf8');
  // Only table definitions, never the destructive schema reset or Supabase services.
  await db.exec(schema.slice(schema.indexOf('  create table admins ('), schema.indexOf('  -- 2) Row Level Security')));
  // Ensure migration creates its column, rather than relying on the fresh schema.
  await db.exec('alter table products drop column coffee_sizes, drop column size, drop column bulk_unit_price, drop column discount_ends_at;');
  const migration = await readFile('supabase/run-all-updates.sql', 'utf8');
  const trainingMarker = '-- Admin-managed weekend training dates.';
  assert.ok(migration.includes(trainingMarker), 'run-all-updates must include the training setup');
  assert.equal(migration.slice(migration.indexOf(trainingMarker), migration.indexOf('-- BEGIN approved stock top-up')).trim(),
    schema.slice(schema.indexOf(trainingMarker)).trim(), 'Training setup must match the standalone schema');
  await db.exec(`
    insert into categories(id, name, icon) values (90001, 'Нэг удаа', 'https://example.test/custom.svg');
    insert into subcategories(id, category_id, name) values (90001, 90001, 'Custom'), (90002, 90001, 'Соруул');
    insert into products(id, name, tag, warehouse_unit_stock) values (90001, 'Existing product', 'алдартай', 17);
    insert into orders(order_number, customer_name, subtotal) values ('KEEP-ORDER', 'Existing customer', 12345);
    create function decrement_stock(bigint, text, int) returns void language plpgsql as $$ begin return; end $$;
    create table training_registrations (
      id bigint generated by default as identity primary key, name text not null, phone text not null,
      training_date date not null, payment_status text default 'pending', qpay_invoice_id text, created_at timestamptz default now()
    );
    insert into training_registrations(id,name,phone,training_date,payment_status)
      values (90001,'Existing student','99112233','2099-06-07','paid');
  `);
  await db.exec(migration);
  await db.exec(migration); // Rerunning the migration must remain safe.
  assert.deepEqual((await db.query('select name,payment_status,schedule_reserved from training_registrations where id=90001')).rows[0],
    { name: 'Existing student', payment_status: 'paid', schedule_reserved: false });
  assert.equal((await db.query('select count(*)::int as n from subcategories where category_id = 90001')).rows[0].n, 8);
  assert.equal((await db.query('select name from subcategories where id = 90001')).rows[0].name, 'Custom');
  assert.equal((await db.query('select name from subcategories where id = 90002')).rows[0].name, 'Соруул');
  assert.equal((await db.query('select icon from categories where id = 90001')).rows[0].icon, 'https://example.test/custom.svg');
  assert.deepEqual((await db.query('select tag, warehouse_unit_stock from products where id = 90001')).rows[0], { tag: 'бестселлэр', warehouse_unit_stock: 17 });
  assert.equal(Number((await db.query("select subtotal from orders where order_number = 'KEEP-ORDER'")).rows[0].subtotal), 12345);
  assert.equal((await db.query("select count(*)::int as n from pg_publication_tables where pubname = 'supabase_realtime'")).rows[0].n, 2);
  assert.equal((await db.query("select has_function_privilege('anon', 'decrement_stock(bigint,text,int)', 'execute') as allowed")).rows[0].allowed, false);
  assert.equal((await db.query("select has_function_privilege('anon', 'restore_stock(bigint,text,int)', 'execute') as allowed")).rows[0].allowed, false);
  await db.exec(await readFile('supabase/tests/coffee_sizes.sql', 'utf8'));
  await testTrainingSQL(db);
  await db.exec('begin');
  await db.exec(`
    delete from stock_topup_audit; delete from stock_topup_runs;
    insert into products(id,name,unit_price,box_price,warehouse_unit_stock,warehouse_box_stock) values
      (91001,'Empty',100,0,0,0),(91002,'Odd',100,500,3,5);
    insert into products(id,name,unit_price,box_price,warehouse_unit_stock,warehouse_box_stock,unified_stock,box_per_box)
      values(91003,'Shared',100,600,7,1,true,6);
    insert into brands(name) values ('Jack''s Coffee') on conflict do nothing;
    insert into categories(id,name) values(91001,'Кофе');
    insert into products(id,name,brand_id,category_id,coffee_sizes) values
      (91004,'Sizes',(select id from brands where name='Jack''s Coffee'),91001,
       '{"size_1kg":{"price":100,"stock":0},"size_250g":{"price":50,"stock":3}}');
  `);
  const topup = migration.slice(migration.indexOf('-- BEGIN approved stock top-up'), migration.indexOf('-- END approved stock top-up'));
  await db.exec(topup);
  const stocks = (await db.query('select id,warehouse_unit_stock as units,warehouse_box_stock as boxes,coffee_sizes from products where id between 91001 and 91004 order by id')).rows;
  assert.equal(stocks[0].units,10);
  assert.equal(stocks[0].boxes,0);
  assert.equal(stocks[1].units,14);
  assert.equal(stocks[1].boxes,16);
  assert.equal(stocks[2].units,72);
  assert.equal(stocks[2].boxes,12);
  assert.equal(stocks[3].coffee_sizes.size_1kg.stock,10);
  assert.equal(stocks[3].coffee_sizes.size_250g.stock,14);
  await db.exec(topup);
  assert.deepEqual((await db.query('select id,warehouse_unit_stock as units,warehouse_box_stock as boxes,coffee_sizes from products where id between 91001 and 91004 order by id')).rows, stocks);
  await db.exec('rollback');
  console.log('PASS one-time even stock top-up, disabled options, shared inventory and coffee sizes; rerun does not add twice');
  console.log('PASS PostgreSQL migration, repeat apply, independent stock, server pricing, rollback, restore and brand validation');
  console.log('PASS supplied SQL merge: preserved products/orders/subcategory IDs/custom icons, idempotent defaults, Realtime and legacy void function upgrade');
} catch (error) {
  console.error(error.message, error.where || '', error.detail || '', error.position || '');
  process.exitCode = 1;
} finally { await db.close(); }
