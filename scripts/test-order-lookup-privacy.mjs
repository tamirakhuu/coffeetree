import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
try {
  await db.exec('create role anon; create role authenticated;');
  await db.exec(`
    create table orders (
      order_number text primary key,
      phone text,
      status text default 'pending',
      payment_status text default 'paid',
      subtotal numeric,
      receipt_type text default 'individual',
      register_number text,
      delivery_method text default 'pickup',
      delivery_fee numeric default 0,
      box_count integer default 0,
      created_at timestamptz default now()
    );
    create table order_items (
      id bigint generated by default as identity primary key,
      order_number text not null references orders(order_number) on delete cascade,
      product_id bigint,
      product_name text,
      option_type text,
      option_label text,
      qty int,
      line_total numeric
    );
  `);

  const migration = await readFile('supabase/run-all-updates.sql', 'utf8');
  const startMarker = 'create or replace function public.expire_stale_orders() returns void';
  const endMarker = 'grant execute on function public.lookup_orders_by_phone(text) to anon, authenticated;';
  const startIdx = migration.indexOf(startMarker);
  const endIdx = migration.indexOf(endMarker);
  assert.ok(startIdx > -1 && endIdx > -1, 'expire_stale_orders/lookup_orders_by_phone markers not found in run-all-updates.sql');
  await db.exec(migration.slice(startIdx, endIdx + endMarker.length));

  await db.exec(`
    insert into orders(order_number, phone, status, subtotal, delivery_method, delivery_fee, receipt_type, register_number, box_count)
    values ('ORD-1', '99001122', 'pending', 55000, 'delivery', 15000, 'company', '1234567', 2);
    insert into order_items(order_number, product_id, product_name, option_type, option_label, qty, line_total)
    values ('ORD-1', 1, 'Lavazza кофе', 'unit', 'ширхэг', 2, 40000);
  `);

  await db.exec('set role anon');
  const { rows } = await db.query('select lookup_orders_by_phone($1) as result', ['99001122']);
  await db.exec('reset role');
  const [order] = rows[0].result;

  assert.ok(order, 'Expected one order to be returned for the phone number');
  assert.deepEqual(Object.keys(order).sort(), ['createdAt', 'deliveryMethod', 'orderNumber', 'status'],
    'lookup_orders_by_phone must return exactly orderNumber, status, deliveryMethod, createdAt');
  assert.equal(order.orderNumber, 'ORD-1');
  assert.equal(order.status, 'pending');
  assert.equal(order.deliveryMethod, 'delivery');
  assert.ok(order.createdAt);

  const leaked = JSON.stringify(order);
  assert.ok(!leaked.includes('1234567'), 'register number must not leak');
  assert.ok(!leaked.includes('Lavazza'), 'product name must not leak');
  assert.ok(!leaked.includes('55000'), 'subtotal must not leak');
  assert.ok(!leaked.includes('15000'), 'delivery fee must not leak');

  console.log('PASS lookup_orders_by_phone returns only orderNumber/status/deliveryMethod/createdAt; items, amounts, address and register number stay private');
} catch (error) {
  console.error(error.message, error.where || '', error.detail || '', error.position || '');
  process.exitCode = 1;
} finally {
  await db.close();
}
